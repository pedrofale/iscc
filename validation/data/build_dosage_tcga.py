"""Build the per-gene dosage-response table of TCGA breast tumours, for calibrating iscc's s_g.

iscc writes a gene's expression per haplotype as ``base_g / 2 * d(c; s_g)`` with
``d(c; s) = max(1 + s * (min(c, sat/2) - 1), 0)`` for ``c >= 1`` copies and ``d(0) = 0``
(``Cell.get_exp_alleles``), and draws the per-gene dosage sensitivity ``s_g`` from a prior. This
script measures the real per-gene dosage response, and the response iscc's law gives on the same
samples, so ``validation/validate_dosage.py`` can fit that prior without the TCGA files.

Data (TCGA PanCanAtlas, open access, https://gdc.cancer.gov/about-data/publications/pancanatlas,
and GENCODE v19 for hg19 gene positions), all in ``--data``:

* ``TCGA_mastercalls.abs_tables_JSedit.fixed.txt``: ABSOLUTE purity and ploidy per sample.
* ``TCGA_mastercalls.abs_segtabs.fixed.txt``: ABSOLUTE allele-specific integer copy number of the
  cancer cells per segment.
* ``merged_sample_quality_annotations.tsv``: cancer type and the ``Do_not_use`` flag per aliquot.
* ``EBPlusPlusAdjustPANCAN_IlluminaHiSeq_RNASeqV2.geneExp.tsv``: batch-corrected RSEM expression.
* ``gencode.v19.annotation.gtf.gz``: gene coordinates.

Per gene, over the primary tumours of ``--cancer`` with an ABSOLUTE call and RNA, the covariate is
the copy ratio the bulk sample would show under linear dosage, adjusted for purity ``p`` and ploidy
``P`` (normal cells are diploid):

    z = log2( ((1 - p) * 2 + p * C) / ((1 - p) * 2 + p * P) )

where ``C`` is the gene's total copy number in the cancer cells. ``log2(expression + 1)`` is
regressed on ``z`` with purity and ploidy as covariates; the slope is 1 under linear dosage and 0
for a fully buffered gene. ``z`` assumes the gene is expressed equally in tumour and normal cells, so
a gene expressed mostly by tumour cells gets a slope above 1 and a stromal gene one near 0: this slope
mixes dosage with cell-type specificity.

The primary measure (columns ``*_hp``) is therefore tumour-intrinsic: only tumours of purity at least
``HIGH_PURITY``, with covariate ``x = log2(C / P)`` (purity and ploidy still covariates), against
iscc's law in tumour cells alone. Both measures are also run on the gains side (covariate >= 0) and
the losses side (<= 0) separately, and on expression generated by iscc's law from each sample's
allele-specific copy number at ``s`` on a grid, normalised by the sample's genome-wide mean at
``--s-ref``, which plays the part of library-size normalisation.

Writes ``--out`` (default ``validation/data/dosage_tcga_brca.csv.gz``), one row per gene, and a
summary JSON beside it. Run on a machine with ~16 GB of memory: the expression matrix is 1.9 GB.

Usage:  python validation/data/build_dosage_tcga.py --data /path/to/tcga_pancan [--cancer BRCA]
"""
import argparse
import gzip
import json
import os
import re

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
S_GRID = np.round(np.linspace(0.0, 1.0, 11), 2)
SAT_ALLELE = 4          # iscc's paper regime: dosage_saturation 8 in total copy number
MIN_SAMPLES = 100
MIN_SIDE = 30           # samples on one side of z = 0 for a gains-only or losses-only slope
HIGH_PURITY = 0.7       # purity floor of the tumour-intrinsic measure


def load_samples(data, cancer):
    """Primary tumours of `cancer` with an ABSOLUTE call and usable RNA: id -> (purity, ploidy)."""
    q = pd.read_csv(os.path.join(data, "merged_sample_quality_annotations.tsv"), sep="\t", dtype=str)
    q = q[(q["cancer type"] == cancer)]
    bad = set(q.loc[q["Do_not_use"].str.lower() == "true", "aliquot_barcode"])
    rna = q[(q["platform"] == "IlluminaHiSeq_RNASeqV2") & ~q["aliquot_barcode"].isin(bad)]
    rna = rna[rna["aliquot_barcode"].str[13:15] == "01"]
    dna = q[(q["platform"] == "Genome_Wide_SNP_6") & ~q["aliquot_barcode"].isin(bad)]
    abs_t = pd.read_csv(os.path.join(data, "TCGA_mastercalls.abs_tables_JSedit.fixed.txt"), sep="\t")
    abs_t = abs_t[(abs_t["call status"] == "called") & abs_t["purity"].notna() & abs_t["ploidy"].notna()]
    abs_t = abs_t[abs_t["sample"].isin(set(dna["aliquot_barcode"]))]
    abs_t = abs_t.drop_duplicates("array").set_index("array")
    rna_by_sample = rna.assign(sid=rna["aliquot_barcode"].str[:15]).drop_duplicates("sid")
    rna_by_sample = rna_by_sample.set_index("sid")["aliquot_barcode"]
    ids = sorted(set(abs_t.index) & set(rna_by_sample.index))
    return ids, abs_t.loc[ids, "purity"].astype(float), abs_t.loc[ids, "ploidy"].astype(float), \
        rna_by_sample.loc[ids]


def load_genes(data):
    """Autosomal genes of GENCODE v19: symbol -> (chrom, midpoint). Symbols on two loci are dropped."""
    rows = []
    with gzip.open(os.path.join(data, "gencode.v19.annotation.gtf.gz"), "rt") as f:
        for line in f:
            if line.startswith("#"):
                continue
            c = line.split("\t", 8)
            if c[2] != "gene":
                continue
            chrom = c[0].removeprefix("chr")
            if not chrom.isdigit():
                continue
            name = re.search(r'gene_name "([^"]+)"', c[8]).group(1)
            rows.append((name, int(chrom), (int(c[3]) + int(c[4])) // 2))
    g = pd.DataFrame(rows, columns=["gene", "chrom", "mid"])
    dup = g["gene"].duplicated(keep=False)
    return g[~dup].set_index("gene")


def load_expression(data, aliquots):
    path = os.path.join(data, "EBPlusPlusAdjustPANCAN_IlluminaHiSeq_RNASeqV2.geneExp.tsv")
    header = pd.read_csv(path, sep="\t", nrows=0).columns
    keep = [header[0]] + [a for a in header[1:] if a in set(aliquots)]
    e = pd.read_csv(path, sep="\t", usecols=keep, index_col=0, dtype={a: np.float32 for a in keep[1:]})
    sym = e.index.str.split("|").str[0]
    e = e[(sym != "?") & ~pd.Index(sym).duplicated(keep=False)]
    e.index = e.index.str.split("|").str[0]
    return e


def gene_copy_number(data, ids, genes):
    """(n_genes, n_samples) arrays of the two haplotype copy numbers at each gene's midpoint."""
    seg = pd.read_csv(os.path.join(data, "TCGA_mastercalls.abs_segtabs.fixed.txt"), sep="\t",
                      usecols=["Sample", "Chromosome", "Start", "End", "Modal_HSCN_1", "Modal_HSCN_2"])
    seg["Sample"] = seg["Sample"].str[:15]
    seg = seg[seg["Sample"].isin(set(ids))]
    seg["Chromosome"] = pd.to_numeric(seg["Chromosome"].astype(str).str.removeprefix("chr"),
                                      errors="coerce")
    seg = seg.dropna(subset=["Chromosome", "Modal_HSCN_1", "Modal_HSCN_2"])
    n_g = len(genes)
    c1 = np.full((n_g, len(ids)), np.nan, dtype=np.float32)
    c2 = np.full((n_g, len(ids)), np.nan, dtype=np.float32)
    col = {s: j for j, s in enumerate(ids)}
    chrom = genes["chrom"].to_numpy()
    mid = genes["mid"].to_numpy()
    for (s, ch), d in seg.groupby(["Sample", "Chromosome"]):
        d = d.sort_values("Start")
        rows = np.flatnonzero(chrom == int(ch))
        if not len(rows):
            continue
        k = np.searchsorted(d["Start"].to_numpy(), mid[rows], side="right") - 1
        ok = (k >= 0) & (mid[rows] <= d["End"].to_numpy()[np.clip(k, 0, None)])
        j = col[s]
        c1[rows[ok], j] = d["Modal_HSCN_1"].to_numpy()[k[ok]]
        c2[rows[ok], j] = d["Modal_HSCN_2"].to_numpy()[k[ok]]
    return c1, c2


def iscc_dosage(c, s):
    """iscc's per-haplotype dosage relative to one copy (Cell.get_exp_alleles), saturation 4."""
    d = np.maximum(1.0 + s * (np.minimum(c, SAT_ALLELE) - 1.0), 0.0)
    return np.where(c > 0, d, 0.0)


def iscc_total(c1, c2, s):
    """iscc's "total" dosage law relative to the diploid gene (Cell.get_exp_alleles), saturation 8."""
    c = c1 + c2
    return np.where(c > 0, np.maximum(1.0 + s * (np.minimum(c, 2 * SAT_ALLELE) / 2.0 - 1.0), 0.0), 0.0)


def slope(X, y):
    """OLS of y on the columns of X (column 1 is the covariate of interest): slope and its SE."""
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    resid = y - X @ beta
    dof = len(y) - X.shape[1]
    if dof <= 0:
        return np.nan, np.nan
    cov = np.linalg.pinv(X.T @ X) * float(resid @ resid) / dof
    return float(beta[1]), float(np.sqrt(max(cov[1, 1], 0.0)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--cancer", default="BRCA")
    ap.add_argument("--s-ref", type=float, default=0.7,
                    help="s used for the genome-wide normalisation of iscc's expression")
    ap.add_argument("--out", default=os.path.join(HERE, "dosage_tcga_brca.csv.gz"))
    a = ap.parse_args()

    ids, purity, ploidy, aliquots = load_samples(a.data, a.cancer)
    genes = load_genes(a.data)
    expr = load_expression(a.data, set(aliquots))
    expr = expr[expr.index.isin(genes.index)]
    expr = expr[[aliquots[s] for s in ids]]
    genes = genes.loc[expr.index]
    c1, c2 = gene_copy_number(a.data, ids, genes)
    y_all = np.log2(expr.to_numpy(dtype=np.float64) + 1.0)
    p = purity.to_numpy()
    P = ploidy.to_numpy()

    total = c1 + c2
    z_all = np.log2(((1 - p) * 2 + p * total) / ((1 - p) * 2 + p * P))
    # iscc's expression of every gene in every sample at s_ref, for the genome-wide normalisation
    r_ref = (iscc_dosage(c1, a.s_ref) + iscc_dosage(c2, a.s_ref)) / 2.0
    norm = (1 - p) + p * np.nanmean(r_ref, axis=0)
    hp = p >= HIGH_PURITY
    x_all = np.log2(total / P)
    norm_t = np.nanmean(r_ref, axis=0)        # tumour cells alone
    norm_k = np.nanmean(iscc_total(c1, c2, a.s_ref), axis=0)    # the same under the "total" law

    out = []
    for gi, gene in enumerate(genes.index):
        ok = np.isfinite(z_all[gi]) & np.isfinite(y_all[gi])
        n = int(ok.sum())
        if n < MIN_SAMPLES:
            continue
        z, y, pp, PP = z_all[gi, ok], y_all[gi, ok], p[ok], P[ok]
        X = np.column_stack([np.ones(n), z, pp, PP])
        b, se = slope(X, y)
        row = dict(gene=gene, chrom=int(genes.at[gene, "chrom"]), mid=int(genes.at[gene, "mid"]), n=n,
                   sd_z=float(np.std(z)), mean_expr=float(np.mean(y)), beta=b, se=se)
        for side, m in (("gain", z >= 0), ("loss", z <= 0)):
            if m.sum() >= MIN_SIDE and (z[m] != 0).sum() >= MIN_SIDE // 3:
                row[f"beta_{side}"], row[f"se_{side}"] = slope(X[m], y[m])
            else:
                row[f"beta_{side}"], row[f"se_{side}"] = np.nan, np.nan
            row[f"n_{side}"] = int(m.sum())
        a1, a2 = c1[gi, ok], c2[gi, ok]
        for s in S_GRID:
            r = (iscc_dosage(a1, s) + iscc_dosage(a2, s)) / 2.0
            ym = np.log2(((1 - pp) + pp * r) / norm[ok])
            row[f"m_{s:.1f}"] = slope(X, ym)[0]
            for side, m in (("gain", z >= 0), ("loss", z <= 0)):
                row[f"m{side[0]}_{s:.1f}"] = (slope(X[m], ym[m])[0]
                                              if np.isfinite(row[f"beta_{side}"]) else np.nan)
        # tumour-intrinsic: high-purity tumours, covariate log2(C / P), iscc's law in tumour cells alone
        okh = np.isfinite(x_all[gi]) & np.isfinite(y_all[gi]) & hp
        row["n_hp"] = nh = int(okh.sum())
        if nh >= MIN_SAMPLES // 2:
            x, yh = x_all[gi, okh], y_all[gi, okh]
            Xh = np.column_stack([np.ones(nh), x, p[okh], P[okh]])
            row["sd_x_hp"] = float(np.std(x))
            row["beta_hp"], row["se_hp"] = slope(Xh, yh)
            sides = {}
            for side, m in (("gain", x >= 0), ("loss", x <= 0)):
                okside = m.sum() >= MIN_SIDE and (x[m] != 0).sum() >= MIN_SIDE // 3
                sides[side] = m if okside else None
                row[f"beta_hp_{side}"], row[f"se_hp_{side}"] = (slope(Xh[m], yh[m]) if okside
                                                                else (np.nan, np.nan))
            h1, h2 = c1[gi, okh], c2[gi, okh]
            for s in S_GRID:
                # columns h*: the "haplotype" law (iscc's default); k*: the "total" law
                for law, r, nrm in (("h", (iscc_dosage(h1, s) + iscc_dosage(h2, s)) / 2.0, norm_t),
                                    ("k", iscc_total(h1, h2, s), norm_k)):
                    ym = np.log2(np.maximum(r, 1e-9) / nrm[okh])
                    row[f"{law}_{s:.1f}"] = slope(Xh, ym)[0]
                    for side, m in sides.items():
                        row[f"{law}{side[0]}_{s:.1f}"] = (slope(Xh[m], ym[m])[0] if m is not None
                                                          else np.nan)
        out.append(row)

    df = pd.DataFrame(out)
    df.to_csv(a.out, index=False, float_format="%.5g")
    summary = dict(cancer=a.cancer, n_samples=len(ids), n_high_purity=int(hp.sum()),
                   high_purity=HIGH_PURITY, n_genes=len(df), s_ref=a.s_ref,
                   purity_median=float(np.median(p)), ploidy_median=float(np.median(P)),
                   s_grid=S_GRID.tolist(), saturation_per_allele=SAT_ALLELE,
                   sources=["TCGA PanCanAtlas (GDC): EBPlusPlusAdjustPANCAN_IlluminaHiSeq_RNASeqV2."
                            "geneExp.tsv, TCGA_mastercalls.abs_segtabs.fixed.txt, TCGA_mastercalls."
                            "abs_tables_JSedit.fixed.txt, merged_sample_quality_annotations.tsv",
                            "GENCODE v19 gene annotation (hg19)"])
    with open(os.path.splitext(os.path.splitext(a.out)[0])[0] + "_summary.json", "w") as f:
        json.dump(summary, f, indent=1)
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
