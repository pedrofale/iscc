"""Supplementary figure: per-gene dosage response in real breast tumours against iscc's prior.

Reads the per-gene table that ``validation/data/build_dosage_tcga.py`` builds from TCGA breast
tumours (``validation/data/dosage_tcga_brca.csv.gz``). For every gene it holds the slope of log
expression on copy number, its standard error, and the slope the same regression gives on expression
generated by iscc's dosage law at ``s`` on a grid, from the same samples' allele-specific copy number.
Two measures are kept:

* ``intrinsic`` (primary): tumours of purity at least 0.7, covariate log2(copy number / ploidy),
  against iscc's law in tumour cells alone. This is the per-cell law that ``s_g`` parameterises.
* ``bulk``: every tumour, with the covariate adjusted for purity on the assumption that the gene is
  expressed equally in tumour and normal cells, so it mixes dosage with cell-type specificity.

The prior of iscc's per-gene dosage sensitivity ``s_g`` is fitted so that the slopes it induces,
with each gene's own estimation noise added, match the real slopes quantile by quantile. Writes the
fit to ``validation/data/dosage_fit.json`` and the figure ``figures/paper1/supp_dosage.pdf``.

Usage:  python validation/paper/supp_dosage.py
"""
import json
import os
import sys

import numpy as np
import pandas as pd
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import style as S  # noqa: E402

DATA = os.path.join(os.path.dirname(HERE), "data")
TABLE = os.path.join(DATA, "dosage_tcga_brca.csv.gz")
FIT = os.path.join(DATA, "dosage_fit.json")
OLD = {"dist": "clipped_normal", "mean": 0.7, "sd": 0.25}      # the paper regime before calibration
Q = np.linspace(0.02, 0.98, 49)
DRAWS = 8
MIN_EXPR = 4.0           # mean log2(RSEM + 1): expressed genes only
MEASURES = {
    "intrinsic": dict(beta="beta_hp", se="se_hp", n="n_hp", sd="sd_x_hp", min_n=100, min_sd=0.15,
                      grid="h", gain=("beta_hp_gain", "se_hp_gain", "hg"),
                      loss=("beta_hp_loss", "se_hp_loss", "hl")),
    "bulk": dict(beta="beta", se="se", n="n", sd="sd_z", min_n=200, min_sd=0.15,
                 grid="m", gain=("beta_gain", "se_gain", "mg"), loss=("beta_loss", "se_loss", "ml")),
}
PRIMARY = "intrinsic"


LAWS = {"haplotype": "h", "total": "k"}       # model columns of the intrinsic measure, per dosage law


def load(measure):
    mz = MEASURES[measure]
    df = pd.read_csv(TABLE)
    keep = (df[mz["n"]] >= mz["min_n"]) & (df[mz["sd"]] >= mz["min_sd"]) & (df["mean_expr"] >= MIN_EXPR)
    keep &= np.isfinite(df[mz["beta"]]) & np.isfinite(df[mz["se"]])
    return df[keep].reset_index(drop=True)


def grid(df, prefix):
    cols = [c for c in df.columns if c.startswith(prefix + "_") and c[len(prefix) + 1:][:1].isdigit()]
    s = np.array([float(c.split("_")[1]) for c in cols])
    return s, df[cols].to_numpy()


def parts(df, measure, law_prefix):
    """The three distributions a prior must match: all copy-number changes, gains only, losses only.
    Each is (real slopes, their SEs, the s grid, iscc's slopes on that grid) over genes with all finite."""
    mz = MEASURES[measure]
    out = {}
    for name, (b, se, pre) in (("all", (mz["beta"], mz["se"], law_prefix)),
                               ("gain", (mz["gain"][0], mz["gain"][1], law_prefix + "g")),
                               ("loss", (mz["loss"][0], mz["loss"][1], law_prefix + "l"))):
        sub = df[np.isfinite(df[b]) & np.isfinite(df[se])]
        sg, ms = grid(sub, pre)
        ok = np.isfinite(ms).all(axis=1)
        out[name] = (sub[b].to_numpy()[ok], sub[se].to_numpy()[ok], sg, ms[ok])
    return out


def draw_s(prior, size, rng):
    if prior["dist"] == "clipped_normal":
        return np.clip(rng.normal(prior["mean"], prior["sd"], size=size), 0.0, 1.0)
    if prior["dist"] == "beta":
        return rng.beta(prior["a"], prior["b"], size=size)
    raise ValueError(prior["dist"])


def induced(prior, s_grid, m, se, seed=0):
    """Slopes iscc's law gives under `prior`, with each gene's own estimation noise added."""
    rng = np.random.default_rng(seed)
    n = m.shape[0]
    s = draw_s(prior, (n, DRAWS), rng)
    idx = np.clip(np.searchsorted(s_grid, s) - 1, 0, len(s_grid) - 2)
    w = (s - s_grid[idx]) / (s_grid[idx + 1] - s_grid[idx])
    rows = np.arange(n)[:, None]
    slope = (1 - w) * m[rows, idx] + w * m[rows, idx + 1]
    return (slope + rng.normal(0.0, 1.0, size=slope.shape) * se[:, None]).ravel()


def joint_loss(prior, P):
    """Quantile mismatch summed over all changes, gains alone and losses alone."""
    return float(sum(np.mean((np.quantile(induced(prior, sg, m, se), Q) - np.quantile(obs, Q)) ** 2)
                     for obs, se, sg, m in P.values()))


def fit(P):
    best = {}

    def clipped(mu, sd):
        return joint_loss({"dist": "clipped_normal", "mean": mu, "sd": sd}, P)
    # iscc's existing family: a coarse grid, then a fine one around its best point
    l, mu0, sd0 = min((clipped(mu, sd), mu, sd) for mu in np.arange(-0.6, 1.81, 0.05)
                      for sd in np.arange(0.05, 1.51, 0.05))
    l, mu0, sd0 = min((clipped(mu, sd), mu, sd) for mu in np.arange(mu0 - 0.05, mu0 + 0.051, 0.01)
                      for sd in np.arange(max(sd0 - 0.05, 0.01), sd0 + 0.051, 0.01))
    best["clipped_normal"] = {"dist": "clipped_normal", "mean": round(float(mu0), 3),
                              "sd": round(float(sd0), 3), "loss": l}
    # the beta family, fitted only as a check on the choice of family: iscc does not implement it
    l, a0, b0 = min((joint_loss({"dist": "beta", "a": a, "b": b}, P), a, b)
                    for a in np.geomspace(0.1, 30, 30) for b in np.geomspace(0.1, 30, 30))
    best["beta"] = {"dist": "beta", "a": round(float(a0), 3), "b": round(float(b0), 3), "loss": l}
    best["old"] = dict(OLD, loss=joint_loss(OLD, P))
    linear = {"dist": "clipped_normal", "mean": 1.0, "sd": 0.0}
    best["linear"] = dict(linear, loss=joint_loss(linear, P))
    return best


def summarise(x):
    q = np.quantile(x, [0.1, 0.25, 0.5, 0.75, 0.9])
    return {"p10": round(float(q[0]), 4), "q1": round(float(q[1]), 4), "median": round(float(q[2]), 4),
            "q3": round(float(q[3]), 4), "p90": round(float(q[4]), 4), "mean": round(float(np.mean(x)), 4)}


def describe(prior, P):
    return {name: summarise(induced(prior, sg, m, se)) for name, (obs, se, sg, m) in P.items()}


def main():
    df = load(PRIMARY)
    res = {"primary": PRIMARY, "n_genes": int(len(df)),
           "real": {name: summarise(v[0]) for name, v in parts(df, PRIMARY, "h").items()},
           "real_se_median": round(float(np.median(df[MEASURES[PRIMARY]["se"]])), 4), "laws": {}}
    for law, pre in LAWS.items():
        P = parts(df, PRIMARY, pre)
        best = fit(P)
        chosen = best["clipped_normal"]                # the family iscc implements
        res["laws"][law] = {"fits": best, "chosen": chosen, "induced_chosen": describe(chosen, P),
                            "induced_old": describe(OLD, P),
                            "n_genes": {k: int(len(v[0])) for k, v in P.items()}}
    law = min(res["laws"], key=lambda k: res["laws"][k]["chosen"]["loss"])
    res["chosen"] = dict(res["laws"][law]["chosen"], dosage_law=law)
    bulk = load("bulk")
    res["bulk_real"] = {name: summarise(v[0]) for name, v in parts(bulk, "bulk", "m").items()}
    res["bulk_n_genes"] = int(len(bulk))
    with open(FIT, "w") as f:
        json.dump(res, f, indent=1)
    print(json.dumps({"real": res["real"], "chosen": res["chosen"],
                      "losses": {k: {f: round(v["fits"][f]["loss"], 4) for f in v["fits"]}
                                 for k, v in res["laws"].items()}}, indent=1))
    draw(df, res)


def _density(ax, x, color, label, fill=False, lw=1.0, ls="-"):
    lo, hi = -0.6, 1.8
    xs = np.linspace(lo, hi, 400)
    kde = stats.gaussian_kde(np.clip(x, lo - 1, hi + 1), bw_method=0.12)
    y = kde(xs)
    if fill:
        ax.fill_between(xs, y, color=color, alpha=0.35, lw=0, label=label)
    else:
        ax.plot(xs, y, color=color, lw=lw, ls=ls, label=label)


def draw(df, res):
    S.setup()
    fig = S.figure("double", 62)
    law = res["chosen"]["dosage_law"]
    new = {k: v for k, v in res["chosen"].items() if k in ("dist", "mean", "sd", "a", "b")}
    P_old, P_new = parts(df, PRIMARY, LAWS["haplotype"]), parts(df, PRIMARY, LAWS[law])
    real_c, old_c, new_c = S.SOURCE["real"], "#C9A227", S.SOURCE["iscc"]
    titles = {"all": "all copy-number changes", "gain": "gains only", "loss": "losses only"}
    for i, (name, letter) in enumerate((("all", "a"), ("gain", "b"), ("loss", "c"))):
        x0 = 12 + i * 58
        ax = S.ax_mm(fig, x0, 8, 48, 38)
        S.panel_letter(fig, letter, x0 - 10, 5)
        obs = P_new[name][0]
        _density(ax, obs, real_c, "TCGA breast tumours", fill=True)
        o_obs, o_se, o_sg, o_m = P_old[name]
        _density(ax, induced(OLD, o_sg, o_m, o_se), old_c, "iscc before (haplotype law, previous prior)", ls="--")
        _, n_se, n_sg, n_m = P_new[name]
        _density(ax, induced(new, n_sg, n_m, n_se), new_c, f"iscc calibrated ({law} law, fitted prior)", lw=1.2)
        for v in (0.0, 1.0):
            ax.axvline(v, color=S.GREY, lw=0.5, ls=":")
        ax.set_xlim(-0.6, 1.8)
        ax.set_yticks([])
        ax.set_xlabel("per-gene dosage slope")
        ax.set_title(titles[name], fontsize=7, color=S.INK)
        S.despine(ax, left=False)
        if i == 0:
            ax.set_ylabel("density of genes")
            ax.legend(frameon=False, fontsize=5.5, loc="upper left")
    S.text_mm(fig, 12, 57.5, f"{res['n_genes']} genes in TCGA breast tumours of purity at least 0.7: slope of log "
                           f"expression on log copy number relative to ploidy (0 = buffered, 1 = linear).\n"
                           f"Each gene's estimation noise is added to iscc's slopes.", fontsize=5.5, color=S.GREY)
    print(S.save(fig, "supp_dosage", stamp=False))


if __name__ == "__main__":
    main()
